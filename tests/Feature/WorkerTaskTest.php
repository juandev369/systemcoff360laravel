    public function test_worker_can_view_assigned_tasks()
    {
        $worker = User::factory()->create([
            'role_id' => 2,
            'estado' => 'activo',
        ]);

        $adminId = User::factory()->create(['role_id' => 1])->id;

        $id_tarea = DB::table('tarea')->insertGetId([
            'nombre' => 'Cosechar Lote A',
            'descripcion' => 'Recolección de café maduro',
            'estado' => 'pendiente',
            'prioridad' => 'alta',
            'creada_por' => $adminId,
            'created_at' => now(),
            'updated_at' => now(),
        ]);

        DB::table('asignacion_tarea')->insert([
            'tarea_id' => $id_tarea,
            'user_id' => $worker->id,
            'fecha_asignacion' => now(),
            'created_at' => now(),
            'updated_at' => now(),
        ]);

        $response = $this->actingAs($worker)->get(route('trabajador.tareas'));

        $response->assertStatus(200);
        $response->assertViewIs('trabajador.tareas.index');
        $response->assertViewHasAll(['tareas', 'total', 'pendientes', 'proceso', 'finalizadas']);
